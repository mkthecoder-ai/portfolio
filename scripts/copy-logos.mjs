#!/usr/bin/env node
// Builds site/src/lib/logos.generated.ts (logo metadata and SVG) and site/public/logos/sprite.svg (what pages
// reference), with every logo following currentColor. Sources: Simple Icons (CC0-1.0) and Devicon (MIT).
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";

const SIMPLE = [
  "kubernetes", "docker", "helm", "dapr", "terraform", "gitlab", "jenkins", "git",
  "sonarqubecloud", "trivy", "jfrog", "prometheus", "grafana", "datadog", "elasticstack",
  "python", "gnubash", "yaml", "postgresql", "redis", "cilium", "github",
];
const DEVICON = {
  azure: { variant: "plain", title: "Microsoft Azure" },
  azuredevops: { variant: "original", title: "Azure DevOps" },
  linkedin: { variant: "plain", title: "LinkedIn" },
};

export function normaliseSvg(svg) {
  return svg
    .replace(/<\?xml[^>]*>/g, "").replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<title>[\s\S]*?<\/title>/g, "").replace(/<defs>[\s\S]*?<\/defs>/g, "").replace(/<style>[\s\S]*?<\/style>/g, "")
    .replace(/<svg\b[^>]*>/, (tag) => tag.replace(/\s(?:width|height|class|style|role|xmlns:xlink)="[^"]*"/g, ""))
    .replace(/\s(?:class|style)="[^"]*"/g, "")
    .replace(/\sfill="(?!none)[^"]*"/g, "")
    .replace(/<svg\b/, '<svg fill="currentColor" aria-hidden="true" focusable="false"')
    .replace(/>\s+</g, "><")
    .trim();
}

/** One sprite for every logo, so pages reference /logos/sprite.svg#logo-<slug> instead of inlining path data. */
export function buildSprite(logos) {
  const symbols = Object.entries(logos).map(([slug, { svg }]) => {
    const viewBox = svg.match(/<svg\b[^>]*\sviewBox="([^"]+)"/)[1];
    const inner = svg.replace(/^<svg\b[^>]*>/, "").replace(/<\/svg>$/, "");
    return `<symbol id="logo-${slug}" viewBox="${viewBox}">${inner}</symbol>`;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join("")}</svg>\n`;
}

async function main() {
  const require = createRequire(import.meta.url);
  const simpleIcons = await import("simple-icons");
  const logos = {};
  for (const slug of SIMPLE) {
    const icon = simpleIcons[`si${slug[0].toUpperCase()}${slug.slice(1)}`];
    if (!icon) throw new Error(`simple-icons has no "${slug}"`);
    logos[slug] = {
      title: icon.title, source: "simple-icons", license: "CC0-1.0",
      svg: `<svg fill="currentColor" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="${icon.path}"/></svg>`,
    };
  }
  const devDir = join(dirname(require.resolve("devicon/package.json")), "icons");
  for (const [slug, { variant, title }] of Object.entries(DEVICON)) {
    const raw = await readFile(join(devDir, slug, `${slug}-${variant}.svg`), "utf8");
    logos[slug] = { title, source: "devicon", license: "MIT", svg: normaliseSvg(raw) };
  }
  await writeFile("site/src/lib/logos.generated.ts", `// Generated by scripts/copy-logos.mjs (npm run logos). Do not edit by hand.
// Simple Icons: CC0-1.0. Devicon: MIT. Brand names and logos are trademarks of their owners.
export const LOGOS = ${JSON.stringify(logos, null, 2)} as const;

export type LogoSlug = keyof typeof LOGOS;
`);
  const rows = Object.entries(logos).map(([slug, l]) => `| ${l.title} | \`${slug}\` | ${l.source} | ${l.license} |`).join("\n");
  await mkdir("site/public/logos", { recursive: true });
  await writeFile("site/public/logos/sprite.svg", buildSprite(logos));
  await writeFile("site/public/logos/LICENSES.md", `# Logo licences

Logos are served from sprite.svg, built from:

- **Simple Icons** (https://simpleicons.org), CC0-1.0
- **Devicon** (https://devicon.dev), MIT. Copyright (c) 2015 konpa.

Brand names and logos are trademarks of their respective owners and are used only to identify the tools.

| Logo | Slug | Source | Licence |
|---|---|---|---|
${rows}
`);
  console.log(`logos: wrote ${Object.keys(logos).length} logos`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
